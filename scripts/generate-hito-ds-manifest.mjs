function buildManifest({ foundationSource, typographyRoles, typographySources }) {
  const primitiveColorSource = parseTokenSection(foundationSource, "primitive-color");
  const primitiveSpacing = parseTokenSection(foundationSource, "primitive-spacing");
  const primitiveRadius = parseTokenSection(foundationSource, "primitive-radius");
  const primitiveMotion = parseTokenSection(foundationSource, "primitive-motion");
  const semanticDark = parseTokenSection(foundationSource, "semantic-color-dark");
  const semanticLight = parseTokenSection(foundationSource, "semantic-color-light");
  const primitiveColor = addColorProvenance(primitiveColorSource, primitiveColorSource);
  const semanticColor = combineSemanticModes(semanticDark, semanticLight, primitiveColorSource);
  const textStyles = typographyRoles
    .filter((role) => role.figmaTextStyle === true)
    .map((role) => buildTextStyle(role, typographySources));
  assertAliasClosure([...primitiveColor, ...semanticDark, ...semanticLight]);

  const sourceDigest = createHash("sha256")
    .update(
      JSON.stringify({
        primitiveColor,
        primitiveSpacing,
        primitiveRadius,
        primitiveMotion,
        semanticColor,
        textStyles,
      }),
    )
    .digest("hex");

  return {
    schemaVersion: 2,
    direction: "code-to-figma",
    sourceDigest: `sha256:${sourceDigest}`,
    sourceOfTruth: {
      tokens: "src/styles/foundations.css",
      typography: "src/lib/hito-typography-roles.ts",
    },
    downstreamScope: {
      figmaVariables: true,
      figmaTextStyles: true,
      figmaComponents: false,
      bidirectionalSync: false,
      excluded: [
        "component families",
        "workout domain colors",
        "visualization geometry",
        "gradients and shadows",
      ],
    },
    collections: {
      primitiveColor,
      semanticColor,
      primitiveSpacing,
      primitiveRadius,
      primitiveMotion,
    },
    collectionContract: {
      primitiveColor: { figmaType: "COLOR", modes: ["Value"] },
      semanticColor: { figmaType: "COLOR", modes: ["Dark", "Light"] },
      primitiveSpacing: { figmaType: "FLOAT", unit: "rem" },
      primitiveRadius: { figmaType: "FLOAT", unit: "px", preserveCssExpression: true },
      primitiveMotion: {
        durationType: "FLOAT",
        durationUnit: "ms",
        easingType: "STRING",
        easingUsage: "code-only",
      },
    },
    textStyles,
  };
}

function parseTokenSection(source, sectionName) {
  const start = `/* @hito-export-start ${sectionName} */`;
  const end = `/* @hito-export-end ${sectionName} */`;
  const startIndex = source.indexOf(start);
  const endIndex = source.indexOf(end);
  if (startIndex < 0 || endIndex < 0 || endIndex <= startIndex) {
    throw new Error(`Missing or invalid Hito export section: ${sectionName}`);
  }

  const section = source.slice(startIndex + start.length, endIndex);
  return [...section.matchAll(/(--[a-z0-9-]+)\s*:\s*([^;]+);/gi)].map((match) =>
    tokenRecord(match[1], normalizeCssValue(match[2])),
  );
}

function tokenRecord(cssVariable, value) {
  const aliasMatch = value.match(/^var\((--[a-z0-9-]+)\)$/i);
  return {
    id: cssVariable.slice(2),
    cssVariable,
    value,
    alias: aliasMatch ? aliasMatch[1].slice(2) : null,
  };
}

function combineSemanticModes(darkTokens, lightTokens, primitiveTokens) {
  const darkByVariable = new Map(darkTokens.map((token) => [token.cssVariable, token]));
  const lightByVariable = new Map(lightTokens.map((token) => [token.cssVariable, token]));
  const darkWithProvenance = new Map(
    addColorProvenance(darkTokens, [...primitiveTokens, ...darkTokens]).map((token) => [
      token.cssVariable,
      token,
    ]),
  );
  const lightWithProvenance = new Map(
    addColorProvenance(lightTokens, [...primitiveTokens, ...lightTokens]).map((token) => [
      token.cssVariable,
      token,
    ]),
  );
  const darkNames = [...darkByVariable.keys()].sort();
  const lightNames = [...lightByVariable.keys()].sort();

  if (JSON.stringify(darkNames) !== JSON.stringify(lightNames)) {
    const darkOnly = darkNames.filter((name) => !lightByVariable.has(name));
    const lightOnly = lightNames.filter((name) => !darkByVariable.has(name));
    throw new Error(
      `Semantic mode mismatch. dark-only=${darkOnly.join(",") || "none"}; light-only=${lightOnly.join(",") || "none"}`,
    );
  }

  const metadataIds = Object.keys(SEMANTIC_COLOR_CHANNELS).sort();
  const semanticIds = darkTokens.map((token) => token.id).sort();
  if (JSON.stringify(metadataIds) !== JSON.stringify(semanticIds)) {
    const missingMetadata = semanticIds.filter((id) => !metadataIds.includes(id));
    const staleMetadata = metadataIds.filter((id) => !semanticIds.includes(id));
    throw new Error(
      `Semantic metadata mismatch. missing=${missingMetadata.join(",") || "none"}; stale=${staleMetadata.join(",") || "none"}`,
    );
  }

  const modeTokens = darkTokens.map((darkToken) => {
    const lightToken = lightByVariable.get(darkToken.cssVariable);
    return {
      id: darkToken.id,
      label: semanticColorLabel(darkToken.id),
      cssVariable: darkToken.cssVariable,
      channels: SEMANTIC_COLOR_CHANNELS[darkToken.id],
      modes: {
        dark: valueRecord(darkWithProvenance.get(darkToken.cssVariable)),
        light: valueRecord(lightWithProvenance.get(lightToken.cssVariable)),
      },
    };
  });

  return modeTokens;
}

function semanticColorLabel(id) {
  return id
    .split("-")
    .map((part) => `${part.charAt(0).toUpperCase()}${part.slice(1)}`)
    .join(" ");
}

function valueRecord(token) {
  return {
    value: token.value,
    alias: token.alias,
    provenance: token.provenance,
  };
}

function addColorProvenance(tokens, lookupTokens) {
  const tokenByVariable = new Map(lookupTokens.map((token) => [token.cssVariable, token]));
  return tokens.map((token) => ({
    ...token,
    provenance: colorProvenance(token, tokenByVariable),
  }));
}

function colorProvenance(token, tokenByVariable, trail = []) {
  if (trail.includes(token.cssVariable)) {
    throw new Error(`Color provenance cycle: ${[...trail, token.cssVariable].join(" -> ")}`);
  }

  if (token.value === "transparent") {
    return {
      kind: "transparent",
      source: token.value,
      references: [],
      aliasChain: [],
      alpha: 0,
    };
  }

  if (token.alias) {
    const aliasVariable = `--${token.alias}`;
    const aliasToken = tokenByVariable.get(aliasVariable);
    if (!aliasToken) {
      throw new Error(
        `Unresolved color provenance alias: ${token.cssVariable} -> ${aliasVariable}`,
      );
    }
    const aliasProvenance = colorProvenance(aliasToken, tokenByVariable, [
      ...trail,
      token.cssVariable,
    ]);
    return {
      kind: "alias",
      source: token.value,
      references: [{ cssVariable: aliasVariable, percentage: null }],
      aliasChain: [aliasToken.id, ...aliasProvenance.aliasChain],
      alpha: aliasProvenance.alpha,
    };
  }

  if (token.value.startsWith("color-mix(")) {
    const references = [...token.value.matchAll(/var\((--[a-z0-9-]+)\)\s*([0-9.]+%)?/gi)].map(
      (match) => ({
        cssVariable: match[1],
        percentage: match[2] ? Number(match[2].slice(0, -1)) : null,
      }),
    );
    const transparentMix = token.value.includes("transparent");
    const singleSourcePercentage = references.length === 1 ? references[0].percentage : null;
    return {
      kind: "formula",
      source: token.value,
      references,
      aliasChain: [],
      alpha:
        transparentMix && singleSourcePercentage !== null ? singleSourcePercentage / 100 : null,
    };
  }

  const alphaMatch = token.value.match(/\/\s*([0-9.]+)%\s*\)/);
  return {
    kind: alphaMatch ? "alpha" : "primitive",
    source: token.value,
    references: [],
    aliasChain: [],
    alpha: alphaMatch ? Number(alphaMatch[1]) / 100 : null,
  };
}

function buildTextStyle(role, sources) {
  const primaryClass = role.className.split(/\s+/)[0];
  const selector = `.${primaryClass}`;
  const sourceOwner = sources.find(({ source }) => findRuleBody(source, selector) !== null);
  if (!sourceOwner)
    throw new Error(`No CSS owner found for typography role ${role.id} (${selector})`);

  const declarations = parseDeclarations(findRuleBody(sourceOwner.source, selector));
  const properties = {};
  for (const property of [
    "font-family",
    "font-size",
    "font-weight",
    "line-height",
    "letter-spacing",
    "text-transform",
    "font-feature-settings",
    "font-variant-numeric",
    "text-wrap",
  ]) {
    if (declarations[property]) properties[property] = declarations[property];
  }

  if (!properties["font-family"]) properties["font-family"] = "var(--font-sans)";
  if (!properties["font-weight"]) properties["font-weight"] = "400";

  const responsive = Object.values(properties).some((value) => value.includes("clamp("));

  return {
    id: role.id,
    label: role.label,
    className: role.className,
    sample: role.sample,
    description: role.description,
    use: role.use,
    cssSpec: role.spec,
    sourcePath: sourceOwner.sourcePath,
    responsive,
    figmaStatus: responsive ? "descriptor-only" : "ready",
    properties,
  };
}

function assertAliasClosure(tokens) {
  const known = new Set(tokens.map((token) => token.id));
  const unresolved = tokens
    .filter((token) => token.alias && !known.has(token.alias))
    .map((token) => `${token.id}->${token.alias}`);

  if (unresolved.length > 0) {
    throw new Error(`Manifest alias targets are unresolved: ${unresolved.join(", ")}`);
  }
}

function findRuleBody(source, selector) {
  const escapedSelector = selector.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const match = source.match(new RegExp(`${escapedSelector}\\s*\\{([^}]*)\\}`, "m"));
  return match?.[1] ?? null;
}

function parseDeclarations(body) {
  return Object.fromEntries(
    [...body.matchAll(/([a-z-]+)\s*:\s*([^;]+);/gi)].map((match) => [
      match[1],
      normalizeCssValue(match[2]),
    ]),
  );
}

function normalizeCssValue(value) {
  return value.replace(/\s+/g, " ").trim();
}

async function assertGeneratedFile(filePath, expected) {
  let actual;
  try {
    actual = await readFile(filePath, "utf8");
  } catch {
    throw new Error(`Missing generated manifest artifact: ${path.relative(rootDir, filePath)}`);
  }
  if (actual !== expected) {
    throw new Error(
      `Generated manifest drifted: ${path.relative(rootDir, filePath)}. Run node --import tsx scripts/generate-hito-ds-manifest.mjs.`,
    );
  }
}
